import { z } from "@jhin/sdk";

/** WebSocket subprotocol of this protocol version. */
export const PROTOCOL = "jhin.v1";
/**
 * Browsers cannot set headers on a WebSocket, so the bearer token travels as a
 * second subprotocol: `jhin.token.<token>`. The server never echoes it back.
 */
export const TOKEN_PROTOCOL_PREFIX = "jhin.token.";

/** Methods handled by the protocol itself; every other method is a command name. */
export const RPC_HELLO = "rpc.hello";
export const RPC_SUBSCRIBE = "rpc.subscribe";
export const RPC_UNSUBSCRIBE = "rpc.unsubscribe";
/** Server → client notification sent once, first, after the server accepted the client. */
export const RPC_READY = "rpc.ready";
/** Server → client notification carrying one event of a subscription. */
export const RPC_EVENT = "rpc.event";
/**
 * Client → server notification: the client is done with the events of a
 * windowed subscription up to `sequence` (D470).
 */
export const RPC_ACK = "rpc.ack";
/**
 * Server → client notification: the server ended a subscription, with why
 * (`SUBSCRIPTION_OVERFLOW`: a windowed subscriber fell too far behind).
 */
export const RPC_SUBSCRIPTION_ENDED = "rpc.subscription.ended";

/**
 * How much of a subscription may be sent and not yet acknowledged (D470):
 * at most `events` events and `bytes` characters of their JSON, as T3 Code's
 * terminal output windows (8 events, 64 KiB).
 */
export const SubscriptionWindow = z.object({
  events: z.number().int().min(1).max(1024),
  bytes: z
    .number()
    .int()
    .min(1024)
    .max(16 * 1024 * 1024),
});
export type SubscriptionWindow = z.infer<typeof SubscriptionWindow>;

export const AckParams = z.object({
  subscription: z.string().min(1),
  sequence: z.number().int().nonnegative(),
});

export const RequestMessage = z.object({
  jsonrpc: z.literal("2.0"),
  id: z.union([z.string(), z.number()]),
  method: z.string().min(1),
  params: z.unknown().optional(),
  /** Jhin extension: the trace id of the request, generated by the server when absent. */
  trace: z.string().min(1).max(128).optional(),
});
export type RequestMessage = z.infer<typeof RequestMessage>;

export interface ErrorObject {
  readonly code: number;
  readonly message: string;
  /** `code` is the Jhin error code (`COMMAND_INPUT_INVALID`, …). */
  readonly data?: { readonly code: string; readonly details?: unknown };
}

export interface ResponseMessage {
  readonly jsonrpc: "2.0";
  readonly id: string | number | null;
  readonly result?: unknown;
  readonly error?: ErrorObject;
  readonly trace?: string;
}

export const SubscribeParams = z.object({
  /**
   * Chosen by the client, unique on its connection: events can arrive before
   * the subscribe call returns (the backlog), and they carry this id.
   */
  subscription: z.string().min(1).max(64),
  stream: z.string().min(1),
  /** Deliver events with a sequence greater than this; default 0 (everything). */
  after: z.number().int().nonnegative().default(0),
  /**
   * Flow control (D470): the client acknowledges each event with `rpc.ack`
   * and the server keeps at most this much unacknowledged. A server that
   * does not know it sends everything as it comes.
   */
  window: SubscriptionWindow.optional(),
});

export const UnsubscribeParams = z.object({ subscription: z.string().min(1) });

/** JSON-RPC error codes; Jhin's own code is in `error.data.code`. */
export const ErrorCodes = {
  PARSE_ERROR: -32700,
  INVALID_REQUEST: -32600,
  METHOD_NOT_FOUND: -32601,
  INVALID_PARAMS: -32602,
  SERVER_ERROR: -32000,
  UNAUTHENTICATED: -32001,
  PERMISSION_DENIED: -32003,
  DISCONNECTED: -32010,
} as const;

/** Maps a thrown error (usually a KernelError) to a JSON-RPC error object. */
export function toErrorObject(error: unknown): ErrorObject {
  const info = error as { code?: unknown; message?: unknown; details?: unknown };
  const code = typeof info?.code === "string" ? info.code : "INTERNAL";
  const message = typeof info?.message === "string" ? info.message : String(error);
  const rpcCode =
    code === "COMMAND_NOT_FOUND"
      ? ErrorCodes.METHOD_NOT_FOUND
      : code === "COMMAND_INPUT_INVALID" || code === "INVALID"
        ? ErrorCodes.INVALID_PARAMS
        : code === "PERMISSION_DENIED"
          ? ErrorCodes.PERMISSION_DENIED
          : ErrorCodes.SERVER_ERROR;
  return {
    code: rpcCode,
    message,
    data: { code, ...(info?.details === undefined ? {} : { details: info.details }) },
  };
}

/** Error thrown by the client: the JSON-RPC error of a call, or a local failure. */
export class RpcError extends Error {
  readonly rpcCode: number;
  /** Jhin error code, e.g. `COMMAND_INPUT_INVALID`, `DISCONNECTED`. */
  readonly code: string;
  readonly details: unknown;

  constructor(error: ErrorObject) {
    super(error.message);
    this.name = "RpcError";
    this.rpcCode = error.code;
    this.code = error.data?.code ?? "INTERNAL";
    this.details = error.data?.details;
  }
}
